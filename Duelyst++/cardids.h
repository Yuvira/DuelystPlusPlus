//Tribe ToString
constexpr std::string TribeToString(eTribe tribe) {
	switch (tribe) {
		case TRIBE_NONE:      return "MINION";
		case TRIBE_GENERAL:   return "GENERAL";
		case TRIBE_ARCANYST:  return "ARCANYST";
		case TRIBE_PET:       return "PET";
		case TRIBE_GOLEM:     return "GOLEM";
		case TRIBE_MECH:      return "MECH";
		case TRIBE_DERVISH:   return "DERVISH";
		case TRIBE_VESPYR:    return "VESPYR";
		case TRIBE_STRUCTURE: return "STRUCTURE";
		case TRIBE_WARMASTER: return "WARMASTER";
	}
	return "???";
}